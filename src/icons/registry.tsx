/** A path's `d`, or `{ d, evenOdd: true }` when Figma exports `fill-rule="evenodd"`. */
type PathSpec = string | { d: string; evenOdd: true };

const renderPaths = (specs: readonly PathSpec[]): ReactNode =>
  specs.map((spec) => {
    const d = typeof spec === 'string' ? spec : spec.d;
    return typeof spec === 'string' ? (
      <path key={d} d={d} fill="currentColor" />
    ) : (
      <path key={d} d={d} fill="currentColor" fillRule="evenodd" clipRule="evenodd" />
    );
  });

/** Exact Figma export (32×32 artboard). */
